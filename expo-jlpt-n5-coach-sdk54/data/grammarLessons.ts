import type { GrammarLesson, GrammarProgressSummary } from '../models';

function makeGrammarLesson(
  order: number,
  folder: string,
  subfolder: string,
  title: string,
  pattern: string,
  level: GrammarLesson['level'],
  goal: string,
  explanation: string,
  formula: string,
  trap: string,
  examples: Array<[string, string, string, string]>
): GrammarLesson {
  const id = `consolidated-${order}-${title
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')}`;
  return {
    id,
    folder,
    subfolder,
    order,
    title,
    pattern,
    level,
    goal,
    explanation,
    formula,
    trap,
    examples: examples.map(([kana, kanji, romaji, fr], index) => ({
      id: `${id}-ex-${index + 1}`,
      kana,
      kanji,
      romaji,
      fr,
      note: 'Exemple orienté vie courante avec structure utile pour le JLPT.',
    })),
  };
}

